from intelhex import IntelHex

ih= IntelHex()

# Fyll hele 64KiB med 0x00 (eller 0xFF)
for i in range(65536):
    ih[i] = 0x00


kode = [
    0x00,
    0x14,
    0x00,
    0x10,
    0x15,
    0x00,
    0x11,
    0x64,
    0x18,
    0x00,
    0x12,
    0x00,
    0x02,
    0x00,
    0x0b,
    0x00,
    0x4f,
    0x12,
    0x00
]

for i in range(len(kode)):
    ih[i] = kode[i]

ih.write_hex_file("memory.hex")
